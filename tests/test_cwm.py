class _ScriptedClient:
    def __init__(self, responses: list[str]) -> None:
        self._responses = list(responses)

    def complete(self, system: str, user: str, stop: list[str] | None = None):
        return self._responses.pop(0)


def test_recorded_client_replays_and_misses(tmp_path: Path) -> None:
    fixture = tmp_path / "fixture.jsonl"
    inner = _ScriptedClient(["first response"])
