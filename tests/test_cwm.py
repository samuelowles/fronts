def test_arena_rejects_the_loser_and_keeps_the_winner() -> None:
    model = ReferenceWorldModel(ReferenceConfig(horizon=10))
    agents = [first_publish_policy, service_policy, hold_policy]
    result = arena_run([model], agents, ArenaConfig(matches_per_pairing=3))
    # The rule, verbatim: reject any agent "worse than the best scoring
    # agent by more than 10% of the observed utility range."
    best = max(result.scores)
    threshold = 0.10 * result.utility_range
    for index in result.rejected:
        assert best - result.scores[index] > threshold
    for index in result.survivors:
        assert best - result.scores[index] <= threshold
    assert set(result.survivors) | set(result.rejected) == {0, 1, 2}
    assert result.survivors, "at least one agent must survive"
    assert 2 in result.rejected, "the hold-everything agent must be rejected"
    assert 0 in result.survivors or 1 in result.survivors


