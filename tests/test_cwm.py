def hold_policy(model: CodeWorldModel, state: dict) -> str:
    legal = model.get_legal_actions(state)
    for action in legal:
        if action == "hold":
            return action
    return legal[0]


def service_policy(model: CodeWorldModel, state: dict) -> str:
    for action in model.get_legal_actions(state):
        if action.startswith("publish") and "cta=reply_keyword" in action:
            return action
    return first_publish_policy(model, state)


