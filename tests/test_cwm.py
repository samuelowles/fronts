class _CapturingRandom(random.Random):
    """Records every (alpha, beta) handed to betavariate."""

    def __init__(self, seed: int) -> None:
        super().__init__(seed)
        self.draws: list[tuple[float, float]] = []

    def betavariate(self, alpha: float, beta: float) -> float:
        self.draws.append((alpha, beta))
        return super().betavariate(alpha, beta)


def test_beta_selection_uses_the_papers_exact_alpha_beta() -> None:
    tree = RefinementTree(
        nodes=[
            RefinementNode("high", 0.8),
            RefinementNode("low", 0.2),
        ],
        heuristic_weight=5.0,
    )
    rng = _CapturingRandom(7)
    tree.select(rng)
    assert rng.draws[0] == pytest.approx((1.0 + 5.0 * 0.8, 1.0 + 0.2 * 5.0))
    assert rng.draws[0] == pytest.approx((5.0, 2.0))
    assert rng.draws[1] == pytest.approx((1.0 + 5.0 * 0.2, 1.0 + 0.8 * 5.0))
    assert rng.draws[1] == pytest.approx((2.0, 5.0))


